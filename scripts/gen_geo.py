def offset(name, base):
    h = hashlib.md5(name.encode("utf-8")).digest()
    dx = ((h[0] / 255) - 0.5) * 0.06   # ±0.03°
    dy = ((h[1] / 255) - 0.5) * 0.06
    return [round(base[0] + dx, 4), round(base[1] + dy, 4)]


def fetch_stations_raw(path):
    url = "https://kyfw.12306.cn/otn/resources/js/framework/station_name.js"
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/124 Safari/537.36",
        "Accept": "*/*", "Referer": "https://kyfw.12306.cn/otn/leftTicket/init"})
    data = urllib.request.urlopen(req, timeout=40).read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    open(path, "wb").write(data)


def main():
    p = os.path.join(ROOT, "scripts", "_stations_raw.js")
    if not os.path.isfile(p):
        print("本地无 station_name.js，正在抓取 12306 官方车站库…")
        try:
            fetch_stations_raw(p)
        except Exception as e:
            print("抓取失败：", e)
            return
    data = open(p, encoding="utf-8", errors="ignore").read()
    i = data.find("'@")
    if i < 0:
        i = data.find("@bjb")
    seg = data[i:]
    if seg.endswith("';"):
        seg = seg[:-2]
    elif seg.endswith("'"):
        seg = seg[:-1]
    recs = seg.split("@")
    st = {}
    for r in recs:
        r = r.strip()
        if not r:
            continue
        f = r.split("|")
        if len(f) >= 8 and f[1]:
            st[f[1]] = f[7]

    geo = {}
    miss_cities = set()
    for name, city in st.items():
        if city in CITY_COORD:
            geo[name] = offset(name, CITY_COORD[city])
        else:
            miss_cities.add(city)

    out = os.path.join(ROOT, "stations_geo.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(geo, f, ensure_ascii=False)
    print(f"✓ stations_geo.json: {len(geo)} 个站有坐标（城市级），"
          f"缺城市坐标的站所在城市 {len(miss_cities)} 个（地图页运行时 Photon 补全）")
    print("缺坐标城市(前30):", sorted(miss_cities)[:30])


if __name__ == "__main__":
    main()
