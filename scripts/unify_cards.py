# ---------------------------------------------------------------- 派生配图
def city_slug_map():
    """从模板的 CITY_IMG 里解析 城市 -> 图片 slug，保持单一数据源。"""
    src = open(TPL, encoding="utf-8").read()
    m = re.search(r"const CITY_IMG\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit("!! 未能在 site_template.html 中找到 CITY_IMG")
    out = {}
    for city, path in re.findall(r"'([^']+)'\s*:\s*'images/pop-([^']+)\.jpg'", m.group(1)):
        out[city] = path
    return out


