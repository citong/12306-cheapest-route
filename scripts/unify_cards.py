# 三种取景：主体居中 / 偏左 / 偏右。
# 城市横幅多为竖构图、地平线偏下，垂直方向统一取"略偏下"的 16:9 窗口，
# 否则很容易只裁到天空。水平方向再做三种偏移，让三张图不至于雷同。
CROPS = [(0.0, 0.44), (0.24, 0.44), (0.52, 0.44)]


def derive_spot_img(src_path, dst_path, idx, total, force=False):
    """从城市横幅裁出第 idx 张景点配图（16:9）。force=True 时覆盖已有文件。"""
    if os.path.exists(dst_path) and not force:
        return False
    if not os.path.exists(src_path):
        return False
    im = Image.open(src_path).convert("RGB")
    w, h = im.size
    target = 16 / 9
    nh = min(h, int(w / target))          # 先由宽度定高
    if nh >= h:                            # 图太窄，则由高度定宽
        nh = h
    nw = int(nh * target)
    if nw > w:
        nw, nh = w, int(w / target)
    fx, fy = CROPS[idx % len(CROPS)]
    x0 = int(max(0, min(w - nw, w * fx)))
    y0 = int(max(0, min(h - nh, h * fy)))
    im2 = im.crop((x0, y0, x0 + nw, y0 + nh))
    if im2.width > 520:
        im2 = im2.resize((520, max(1, round(520 / target))), Image.LANCZOS)
    # 轻微差异化调色，让三张图不显得完全雷同
    if idx % 3 == 1:
        im2 = ImageEnhance.Color(im2).enhance(1.12)
    elif idx % 3 == 2:
        im2 = ImageEnhance.Brightness(im2).enhance(1.05)
    im2.save(dst_path, "JPEG", quality=74, optimize=True, progressive=True)
    return True


def main():
    force = "--force" in sys.argv
    slug = city_slug_map()
    attr = json.load(open(ATTR, encoding="utf-8"))
    n_city = n_spot = n_img = n_miss = 0

    for city, v in attr.items():
        # --- 1) 城市速览 ---
        if not v.get("days") and city in CITY:
            d, s, f = CITY[city]
            v["days"], v["season"], v["food"] = d, s, f
            n_city += 1
        if city in TIPS:
            v["tip"] = TIPS[city]

        # --- 2) 景点字段 + 配图 ---
        rows = SPOT.get(city)
        sl = slug.get(city)
        src = os.path.join(IMG, "pop-%s.jpg" % sl) if sl else None
        for i, sp in enumerate(v.get("spots") or []):
            if rows and i < len(rows):
                t, p, b = rows[i]
                sp.setdefault("t", t); sp.setdefault("p", p); sp.setdefault("b", b)
                if any(k in sp for k in ("t", "p", "b")):
                    n_spot += 1
            # 12 城的实景点图受保护，任何情况下都不覆盖
            if city in REAL_CITIES and sp.get("img"):
                continue
            if sp.get("img") and sl and os.path.exists(os.path.join(ROOT, sp["img"])):
                # 已有图（非受保护城市）也只在 force 时重生成
                if not force:
                    continue
            if sl:
                dst = "images/spot-%s-%d.jpg" % (sl, i + 1)
                if derive_spot_img(src, os.path.join(ROOT, dst), i,
                                   len(v["spots"]), force=force):
                    n_img += 1
                sp["img"] = dst

        # --- 3) 配图自检：任何景点都必须有图 ---
        for sp in (v.get("spots") or []):
            p = sp.get("img")
            if p and not os.path.exists(os.path.join(ROOT, p)):
                sp.pop("img")   # 文件不存在则撤掉，交由 SVG 兜底
                n_miss += 1

    with open(ATTR, "w", encoding="utf-8") as f:
        json.dump(attr, f, ensure_ascii=False, indent=2)

    # --- 统计校验 ---
    total = len(attr)
    full = sum(1 for v in attr.values() if v.get("days"))
    withimg = sum(1 for v in attr.values()
                  if all(s.get("img") for s in (v.get("spots") or [])))
    nospot = [k for k, v in attr.items() if not (v.get("spots") or [])]
    print("城市总数            : %d" % total)
    print("含城市速览          : %d" % full)
    print("全部景点都有配图    : %d" % withimg)
    print("补齐城市速览字段    : %d" % n_city)
    print("补齐景点字段        : %d" % n_spot)
    print("新派生景点图        : %d" % n_img)
    if n_miss:
        print("撤销失效图引用      : %d" % n_miss)
    if nospot:
        print("!! 无景点数据        : %s" % nospot)
    assert full == total, "仍有城市缺速览字段"
    assert withimg == total, "仍有城市存在无图景点"


if __name__ == "__main__":
    main()
